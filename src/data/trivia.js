// 從指定難度抽 n 題（不給難度則全題庫）。Fisher–Yates 洗牌。
export function pickRound(n = 5, difficulty = null) {
  const arr = TRIVIA.filter((t) => !difficulty || t.difficulty === difficulty);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr.slice(0, Math.min(n, arr.length));
}
